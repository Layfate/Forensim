"""Builds supabase/migrations/20261123000001_syllabus_reviewers.sql from reviewers_part*.py.

Run from this folder:  python build_reviewers.py
Checks that every image exists in app/src/main/assets/lesson-media and has a credit in
media_credits.json, then writes an idempotent migration (re-running replaces the reviewer lessons)."""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import reviewers_part1, reviewers_part2  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
ASSETS = os.path.join(ROOT, "app", "src", "main", "assets", "lesson-media")
OUT = os.path.join(ROOT, "supabase", "migrations", "20261123000001_syllabus_reviewers.sql")
credits = json.load(open(os.path.join(HERE, "media_credits.json"), encoding="utf-8"))

modules = {**reviewers_part1.MODULES, **reviewers_part2.MODULES}
errors, used_images, videos = [], set(), set()


def section_json(s):
    out = {"heading": s["heading"], "body": s["body"]}
    if "image" in s:
        key = s["image"].removesuffix(".webp")
        used_images.add(s["image"])
        if not os.path.exists(os.path.join(ASSETS, s["image"])):
            errors.append(f"missing image file: {s['image']}")
        if key not in credits:
            errors.append(f"missing credit: {key}")
        out.update(image=s["image"], caption=s.get("caption"), credit=credits.get(key, {}).get("credit"))
    if "video" in s:
        if not re.fullmatch(r"[A-Za-z0-9_-]{11}", s["video"]):
            errors.append(f"bad video id: {s['video']}")
        videos.add(s["video"])
        out.update(video=s["video"], video_title=s.get("video_title"))
    return out


def dq(tag, text):
    if f"${tag}$" in text:
        raise SystemExit(f"text contains ${tag}$")
    return f"${tag}${text}${tag}$"


parts = ["-- Syllabus-aligned reviewer lessons (WCC Forensic 1 to 6) with images and in-app videos.",
         "-- Generated by supabase/content/build_reviewers.py; edit the Python sources, not this file.",
         "-- Lessons are published and approved (confirmed by the instructor, 2026-11-23).",
         ""]
total = 0
for slug, lessons in modules.items():
    titles = [l["title"] for l in lessons]
    rows = []
    for i, l in enumerate(lessons, start=1):
        sections = json.dumps([section_json(s) for s in l["sections"]], ensure_ascii=False)
        terms = json.dumps([{"term": t, "definition": d} for t, d in l["terms"]], ensure_ascii=False)
        refs = json.dumps(l["refs"], ensure_ascii=False)
        rows.append(f"    (m, base + {i}, {dq('t', l['title'])}, {l['minutes']}, true, 'approved',\n"
                    f"     {dq('j', sections)}::jsonb,\n     {dq('j', terms)}::jsonb,\n     {dq('j', refs)}::jsonb)")
    total += len(lessons)
    title_array = ", ".join(dq("t", t) for t in titles)
    parts.append(f"""do $mig$
declare
  m uuid;
  base int;
begin
  for m in select id from public.modules where slug = '{slug}' loop
    delete from public.lessons where module_id = m and title = any (array[{title_array}]);
    select coalesce(max(position), 0) into base from public.lessons where module_id = m;
    insert into public.lessons (module_id, position, title, reading_minutes, published, review_status, sections, key_terms, citations) values
{(","+chr(10)).join(rows)};
  end loop;
end $mig$;
""")

unused = sorted(f for f in os.listdir(ASSETS) if f.endswith(".webp") and f not in used_images)
if unused:
    print("note: images not referenced by any lesson:", ", ".join(unused))
if errors:
    raise SystemExit("\n".join(errors))
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(parts))
print(f"wrote {OUT}: {len(modules)} modules, {total} lessons, {len(used_images)} images, {len(videos)} videos")
